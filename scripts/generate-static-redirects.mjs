import { access, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Emits Cloudflare Pages `_redirects` for the two documentation routes that
// only exist to forward somewhere else.
//
// `/docs` and `/docs/<collection>` call `redirect()` in the app, which a static
// export cannot represent: it writes an error shell rather than a 3xx. As real
// Pages redirect rules they stay correct — and become 301s the crawler can
// follow, instead of the 307 the SSR boundary answers today.
//
// A collection's default version is only known from the content service, so the
// rules are generated per build. Without a reachable service the file is still
// written with the `/docs` rule alone, and collection landing paths fall through
// to whatever serves them today.

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(projectRoot, "static-dashboard", "out");
const baseUrl = normalizeBaseUrl(
  process.env.DOCS_SERVICE_URL || process.env.NEXT_PUBLIC_DOCS_SERVICE_URL || "http://127.0.0.1:3001",
);
const token = (process.env.INTERNAL_SERVICE_TOKEN || "").trim();

// Nothing to forward when the export does not carry the documentation tree.
if (!(await exists(path.join(outDir, "docs")))) {
  console.log("No documentation routes in the export; skipping _redirects.");
  process.exit(0);
}

const rules = ["# Generated by scripts/generate-static-redirects.mjs", "/docs /support 301"];

for (const collection of await loadCollections()) {
  const target = collection.defaultVersionSlug || collection.versions?.[0]?.slug;
  if (!collection.slug || !target) continue;
  rules.push(`/docs/${collection.slug} /docs/${collection.slug}/${target} 301`);
}

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, "_redirects"), `${rules.join("\n")}\n`);
console.log(`Wrote ${rules.length - 1} redirect rules to static-dashboard/out/_redirects`);

async function loadCollections() {
  try {
    const response = await fetch(`${baseUrl}/api/v1/docs/collections?lang=zh`, {
      headers: token ? { "X-Service-Token": token, Accept: "application/json" } : { Accept: "application/json" },
    });
    if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
    const payload = await response.json();
    return Array.isArray(payload) ? payload : [];
  } catch (error) {
    console.warn("Skipping collection redirects: content service unavailable", error);
    return [];
  }
}

async function exists(target) {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
}

function normalizeBaseUrl(value) {
  return value.replace(/\/$/, "");
}
