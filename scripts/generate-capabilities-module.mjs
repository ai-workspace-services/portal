import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.resolve(
  projectRoot,
  process.env.CAPABILITIES_MANIFEST || "../.github/capabilities/modules.yaml",
);
const outputPath = path.join(projectRoot, "src/config/capabilities.generated.ts");
const featureTogglePath = path.join(projectRoot, "src/config/feature-toggles.json");
const builtinIndexPath = path.join(projectRoot, "src/modules/extensions/builtin/index.ts");
const checkOnly = process.argv.includes("--check");

const manifest = yaml.load(fs.readFileSync(manifestPath, "utf8"));
const featureToggles = JSON.parse(fs.readFileSync(featureTogglePath, "utf8"));
const builtinIndex = fs.readFileSync(builtinIndexPath, "utf8");
const builtinDirectories = [...builtinIndex.matchAll(/from ['"]\.\/([^'"]+)['"]/g)].map(
  ([, directory]) => directory,
);
const builtinIds = builtinDirectories.map((directory) => {
  const sourcePath = path.join(projectRoot, "src/modules/extensions/builtin", directory, "index.ts");
  const source = fs.readFileSync(sourcePath, "utf8");
  const match = source.match(/id:\s*["'](builtin\.[^"']+)["']/);
  if (!match) throw new Error(`missing builtin extension id in ${sourcePath}`);
  return `portal.builtin.${match[1].slice("builtin.".length).replaceAll("-", "_")}`;
});

const appModules = featureToggles.appModules?.children || {};
const appModuleIds = Object.keys(appModules).map((id) => `portal.app.${id}`);
const manifestIds = new Set(manifest.modules.map((module) => module.id));
const expectedRuntimeIds = [...appModuleIds, ...builtinIds];
const missing = expectedRuntimeIds.filter((id) => !manifestIds.has(id));
if (missing.length > 0) {
  throw new Error(`capability manifest is missing runtime records: ${missing.join(", ")}`);
}

const builtinModules = manifest.modules.filter(
  (module) => module.source === "builtinExtension",
);
const builtinModuleIds = builtinModules.map((module) => module.id);
const missingBuiltinContracts = builtinModules
  .filter((module) => !Array.isArray(module.extension_routes) || module.extension_routes.length === 0)
  .map((module) => module.id);
if (missingBuiltinContracts.length > 0) {
  throw new Error(
    `builtin capability records must declare extension_routes: ${missingBuiltinContracts.join(", ")}`,
  );
}
const sourceBuiltinSet = new Set(builtinIds);
const manifestBuiltinSet = new Set(builtinModuleIds);
if (
  sourceBuiltinSet.size !== manifestBuiltinSet.size ||
  [...sourceBuiltinSet].some((id) => !manifestBuiltinSet.has(id))
) {
  throw new Error(
    `builtin implementation ids do not match the capability manifest: source=${builtinIds.join(", ")} manifest=${builtinModuleIds.join(", ")}`,
  );
}

function normalizeAccessRule(rule = {}) {
  return Object.fromEntries(
    [
      ["requireLogin", rule.require_login],
      ["allowGuests", rule.allow_guests],
      ["roles", rule.roles],
      ["permissions", rule.permissions],
      ["groups", rule.groups],
      ["tenantScoped", rule.tenant_scoped],
    ].filter(([, value]) => value !== undefined),
  );
}

function normalizeRouteContract(route) {
  return {
    id: route.id,
    path: route.path,
    label: route.label,
    ...(route.description === undefined ? {} : { description: route.description }),
    ...(route.match === undefined ? {} : { match: route.match }),
    guard: normalizeAccessRule(route.guard),
    ...(route.redirect === undefined
      ? {}
      : { redirect: route.redirect }),
    ...(route.sidebar === undefined
      ? {}
      : { sidebar: route.sidebar }),
    ...(route.feature_flag === undefined
      ? {}
      : {
          featureFlag: {
            id: route.feature_flag.id,
            title: route.feature_flag.title,
            description: route.feature_flag.description,
            envVar: route.feature_flag.env_var,
            defaultEnabled: route.feature_flag.default_enabled,
          },
        }),
  };
}

const builtinRouteContracts = Object.fromEntries(
  builtinModules.map((module) => [
    module.id,
    module.extension_routes.map(normalizeRouteContract),
  ]),
);

const channelAllowed = (channel, environment) =>
  !channel || environment === "dev" || environment === "uat" || channel === "stable";

const visibleModuleIds = Object.fromEntries(
  ["dev", "uat", "prod"].map((environment) => [
    environment,
    [
      ...Object.entries(appModules)
        .filter(([, node]) => node.enabled !== false && channelAllowed(node.channel, environment))
        .map(([id]) => `portal.app.${id}`),
      ...builtinModuleIds,
    ],
  ]),
);

const generated = `// Generated by scripts/generate-capabilities-module.mjs.
// Do not edit this file directly; edit ai-workspace-services/.github/capabilities/modules.yaml.
export const capabilities = ${JSON.stringify(
  {
    version: manifest.version,
    modules: manifest.modules,
    builtinModuleIds,
    builtinRouteContracts,
    visibleModuleIds,
  },
  null,
  2,
)} as const

export type CapabilityModule = (typeof capabilities.modules)[number]
export type CapabilityEnvironment = keyof typeof capabilities.visibleModuleIds
export type CapabilityAccessRule = {
  requireLogin?: boolean
  allowGuests?: boolean
  roles?: readonly ("user" | "operator" | "admin")[]
  permissions?: readonly string[]
  groups?: readonly string[]
  tenantScoped?: boolean
}
export type CapabilityRouteContract = {
  id: string
  path: string
  label: string
  description?: string
  match?: "exact" | "startsWith"
  guard: CapabilityAccessRule
  redirect?: { unauthenticated?: string; forbidden?: string }
  sidebar?: { section: string; order?: number; hidden?: boolean }
  featureFlag?: {
    id: string
    title: string
    description?: string
    envVar?: string
    defaultEnabled?: boolean
  }
}
`;

if (checkOnly) {
  const current = fs.readFileSync(outputPath, "utf8");
  if (current !== generated) {
    console.error(`capability generated file is stale: ${path.relative(projectRoot, outputPath)}`);
    process.exit(1);
  }
  console.log(`capability generated file is up to date: ${path.relative(projectRoot, outputPath)}`);
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`generated ${path.relative(projectRoot, outputPath)} from ${manifestPath}`);
}
