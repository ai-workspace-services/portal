import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"

const projectRoot = process.cwd()
const configDir = path.join(projectRoot, "src", "config")
const target = path.join(configDir, "runtime-service-config.generated.ts")
const sourceKeys = ["base", "dev", "sit", "uat", "prod"]

const sources = Object.fromEntries(
  await Promise.all(
    sourceKeys.map(async (sourceKey) => {
      const sourcePath = path.join(
        configDir,
        `runtime-service-config.${sourceKey}.yaml`,
      )
      return [sourceKey, await readFile(sourcePath, "utf8")]
    }),
  ),
)

const moduleSource = `// Generated by scripts/generate-runtime-config-module.mjs.\n// Do not edit this file directly; edit runtime-service-config.*.yaml instead.\nexport const runtimeServiceConfigSources = ${JSON.stringify(sources, null, 2)} as const\n`

await writeFile(target, moduleSource, "utf8")
console.log("Generated runtime configuration module.")
