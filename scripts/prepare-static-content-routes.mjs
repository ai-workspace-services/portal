import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Adds the content sections (blogs, docs, products) to the static-dashboard
// export — but only when the content service can actually be reached.
//
// `output: export` has no on-demand rendering: a dynamic route whose
// `generateStaticParams` comes back empty fails the build outright. The VPS
// image (Dockerfile.static-dashboard) and the delivery checks both build
// without a content service, so the sections have to be optional rather than
// checked in. With the service unreachable this leaves the export exactly as it
// was before the content sections existed.
//
//   --auto     (default) include the sections when the service answers
//   --enable   require them; fail when the service does not answer
//   --disable  never include them
//
// The generated routes are re-exports of the real app routes, so there is no
// second copy of a page to keep in sync.

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appRoot = path.join(projectRoot, "static-dashboard", "app");
const mode = readMode(process.argv.slice(2));

// [route directory, module under src/app, extra named exports]
const SECTION_ROUTES = [
  ["blogs", "blogs", ["metadata"]],
  ["blogs/[...slug]", "blogs/[...slug]", ["generateMetadata", "generateStaticParams"]],
  ["docs/[collection]/[...slug]", "docs/[collection]/[...slug]", ["generateMetadata", "generateStaticParams"]],
  ["products/[slug]", "products/[slug]", ["generateStaticParams"]],
  ["products/xconnect", "products/xconnect", []],
  ["products/xworkmate", "products/xworkmate", []],
  ["products/open-platform", "products/open-platform", []],
  ["products/ai-workspace", "products/ai-workspace", []],
];

const SECTION_DIRECTORIES = ["blogs", "docs", "products"];

const enabled = await resolveEnabled();

for (const directory of SECTION_DIRECTORIES) {
  await rm(path.join(appRoot, directory), { recursive: true, force: true });
}

if (!enabled) {
  console.log("Static content sections disabled; static-dashboard exports the base site only.");
  process.exit(0);
}

for (const [routeDir, sourceModule, namedExports] of SECTION_ROUTES) {
  const target = path.join(appRoot, routeDir, "page.tsx");
  await mkdir(path.dirname(target), { recursive: true });
  const importPath = path.relative(path.dirname(target), path.join(projectRoot, "src", "app", sourceModule, "page"));
  const exports = ["default", ...namedExports].join(", ");
  const lines = [
    "// Generated by scripts/prepare-static-content-routes.mjs — do not edit.",
    `export { ${exports} } from ${JSON.stringify(importPath.replaceAll(path.sep, "/"))}`,
  ];
  // Static export cannot render an unknown parameter on demand.
  if (routeDir.includes("[")) lines.push("", "export const dynamicParams = false");
  await writeFile(target, `${lines.join("\n")}\n`);
}

console.log(`Static content sections enabled: ${SECTION_ROUTES.length} routes re-exported into static-dashboard.`);

function readMode(argv) {
  if (argv.includes("--disable")) return "disable";
  if (argv.includes("--enable")) return "enable";
  return "auto";
}

async function resolveEnabled() {
  if (mode === "disable") return false;

  const baseUrl = (process.env.DOCS_SERVICE_URL || process.env.NEXT_PUBLIC_DOCS_SERVICE_URL || "").trim().replace(/\/$/, "");
  const token = (process.env.INTERNAL_SERVICE_TOKEN || "").trim();
  const reason = await probe(baseUrl, token);

  if (!reason) return true;
  if (mode === "enable") throw new Error(`Static content sections requested but the content service is unusable: ${reason}`);
  console.warn(`Static content sections skipped: ${reason}`);
  return false;
}

async function probe(baseUrl, token) {
  if (!baseUrl) return "DOCS_SERVICE_URL is not set";
  try {
    const response = await fetch(`${baseUrl}/api/v1/docs/collections?lang=zh`, {
      headers: token ? { "X-Service-Token": token, Accept: "application/json" } : { Accept: "application/json" },
      signal: AbortSignal.timeout(15_000),
    });
    if (!response.ok) return `${baseUrl} answered ${response.status}`;
    const payload = await response.json();
    if (!Array.isArray(payload) || payload.length === 0) return `${baseUrl} returned no collections`;
    return undefined;
  } catch (error) {
    return `${baseUrl} is unreachable (${error instanceof Error ? error.message : String(error)})`;
  }
}
